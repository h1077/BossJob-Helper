# 3. 模块润色 Prompt
# ═══════════════════════════════════════════════════════════════

def build_optimize_section_prompt(section_type: str, section_data: str, full_resume_context: str = '') -> str:
    """AI 模块润色 — 仅优化指定区块的表达，不改变事实"""
    section_labels = {
        'projects': '项目经历', 'internships': '实习经历', 'education': '教育背景',
        'skills': '专业技能', 'awards': '获奖情况', 'student_work': '学生工作',
    }
    label = section_labels.get(section_type, section_type)

    context = f"""
## 完整简历上下文（供参考）
{ full_resume_context[:2000] }
""" if full_resume_context else ''

    return f"""## 角色
你是一名技术招聘负责人和简历表达教练。
请只润色用户指定的"{ label }"模块，目标是让原有事实更清楚、更专业、更便于面试追问。

## 核心约束
1. 只能润色表达方式（措辞、句式、排列顺序），不得改变事实。
2. 不得新增公司、学校、技能、项目、奖项、数字或结果。
3. 保留原模块的全部条目数量和顺序。
4. star_points 中每条保留原有的字段结构（situation/action/result/keywords）。

## 润色标准
- 项目/实习经历：强化本人动作动词、技术选择、可核验结果
- 专业技能：合并重复关键词，让技能描述更准确
- 教育背景：统一格式、突出亮点
- 获奖情况：改善名称和说明的清晰度

{ FACT_INTEGRITY_RULES }
{ RECRUITMENT_WRITING_RULES }
{ JSON_RULES }

{ context }

## 当前模块（{ label }）
{ section_data[:3000] }

## 输出格式
{{
  "optimized_section": <这里放润色后的模块内容，格式与输入相同>,
  "changes": ["描述真实发生的修改"],
  "suggestions": ["补充事实后可进一步增强的建议"]
}}

注意：如果当前模块没有实质改进空间，optimized_section 与原内容完全一致，changes 为空数组。"""


